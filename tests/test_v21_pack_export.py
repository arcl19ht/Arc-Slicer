def _read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


class _PackExportCase(unittest.TestCase):
    def setUp(self):
        self.old_out_dir = app.OUT_DIR
        self.old_get_ffmpeg = app._get_ffmpeg
        self.old_slice_ogg = app.slice_ogg
        self.old_slice_aff = app.slice_aff
        self.old_render_pack_cover = app.render_pack_cover
        self.td = tempfile.TemporaryDirectory()
        self.root = Path(self.td.name)
        app.OUT_DIR = self.root / "out"
        app._get_ffmpeg = lambda: "ffmpeg"
        self.cover_sources = []
        self.slice_ogg_calls = []
        self.slice_aff_calls = []
        self.logs = []

        def fake_slice_ogg(_in_path, out_path, start, end, speed):
            self.slice_ogg_calls.append((start, end, speed, Path(out_path).parent.name))
            Path(out_path).write_bytes(f"ogg-{start}-{end}-{speed}".encode())

        def fake_slice_aff(_text, _start, _end, speed, warnings=None):
            self.slice_aff_calls.append((_start, _end, speed))
            return f"AudioOffset:0\n-\ntiming(0,{100 * speed:.2f},4.00);\n"

        def fake_cover_renderer(src, dest, log_fn=None):
            self.cover_sources.append(Path(src).name)
            Path(dest).parent.mkdir(parents=True, exist_ok=True)
            Path(dest).write_bytes(b"PNG374x750:" + Path(src).read_bytes())

        app.slice_ogg = fake_slice_ogg
        app.slice_aff = fake_slice_aff
        app.render_pack_cover = fake_cover_renderer
        self.songs_dir = self.root / "songs"
        song = self.songs_dir / "prelude_heavensdoor"
        song.mkdir(parents=True)
        (song / "base.ogg").write_bytes(b"audio")
        (song / "2.aff").write_text("AudioOffset:0\n-\ntiming(0,100.00,4.00);\n", encoding="utf-8")
        self.song_dir = song

    def tearDown(self):
        app.OUT_DIR = self.old_out_dir
        app._get_ffmpeg = self.old_get_ffmpeg
        app.slice_ogg = self.old_slice_ogg
        app.slice_aff = self.old_slice_aff
        app.render_pack_cover = self.old_render_pack_cover
        self.td.cleanup()

    def log(self, text, kind="normal"):
        self.logs.append((text, kind))

    def do_slice(self, *, form=None, songlist=True, packlist=True, current=True, library=False):
        return app.do_slice(
            self.songs_dir,
            "prelude_heavensdoor",
            [{"s": 21000, "e": 22000}],
            1.0,
            self.log,
            form or _form(),
            songlist_enabled=songlist,
            current_export_enabled=current,
            library_export_enabled=library,
            packlist_enabled=packlist,
            duration_getter=lambda _path: 120_000,
        )


class V21PackTemplateTests(unittest.TestCase):
    def test_default_pack_form_uses_source_id(self):
        data = app.default_pack_form_for_song("source_song")
        self.assertEqual(data["pack_id"], "source_song")
        self.assertEqual(data["pack_name"], "source_song")
        self.assertEqual(data["pack_description"], "")
        self.assertEqual(data["pack_section"], "collab")
        self.assertEqual(data["pack_img"], "select_source_song.png")

    def test_pack_template_rejects_invalid_id_and_img(self):
        for overrides in (
            {"pack_id": "bad id"},
            {"pack_id": "中文"},
            {"pack_img": "../x.png"},
            {"pack_img": "C:\\x.png"},
            {"pack_img": "x.jpg"},
        ):
            with self.subTest(overrides=overrides):
                with self.assertRaises(ValueError):
                    app.pack_template_from_form(_form(**overrides), "source")

    def test_upload_cover_requires_existing_png_jpg_or_jpeg(self):
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            png = root / "cover.png"
            jpg = root / "cover.jpg"
            jpeg = root / "cover.jpeg"
            for path in (png, jpg, jpeg):
                path.write_bytes(b"image")
                template = app.pack_template_from_form(
                    _form(pack_cover_source="upload", pack_cover_path=str(path)),
                    "source",
                )
                self.assertEqual(template.cover_path, str(path))
            with self.assertRaises(ValueError):
                app.pack_template_from_form(_form(pack_cover_source="upload", pack_cover_path=str(root / "x.gif")), "source")

    def test_packlist_entry_shape_has_no_unconfirmed_fields(self):
        template = app.pack_template_from_form(_form(), "source")
        entry = app.build_packlist_entry(template)
        self.assertEqual(set(entry), {"id", "section", "plus_character", "name_localized", "description_localized", "img"})
        self.assertEqual(entry["section"], "collab")
        self.assertEqual(entry["plus_character"], -1)

    def test_pack_section_from_form_is_exported_and_unknown_values_fallback(self):
        template = app.pack_template_from_form(_form(pack_section="archive"), "source")
        self.assertEqual(template.section, "archive")
        self.assertEqual(app.build_packlist_entry(template)["section"], "archive")

        for value in (None, "", "unknown_value"):
            with self.subTest(value=value):
                data = _form()
                if value is None:
                    data.pop("pack_section")
                else:
                    data["pack_section"] = value
                template = app.pack_template_from_form(data, "source")
                self.assertEqual(template.section, "collab")

    def test_empty_pack_description_stays_empty_in_template_and_packlist(self):
        template = app.pack_template_from_form(_form(pack_description=""), "source")
        entry = app.build_packlist_entry(template)
        self.assertEqual(template.description, "")
        self.assertEqual(entry["description_localized"]["en"], "")

    def test_cover_crop_geometry_center_crop(self):
        self.assertEqual(app._cover_crop_geometry(1000, 1000), (750, 750, 188, 0))
        self.assertEqual(app._cover_crop_geometry(100, 1000), (374, 3740, 0, 1495))


