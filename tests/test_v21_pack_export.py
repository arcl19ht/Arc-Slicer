def _write_stage(stage: Path, song_id: str, pack_id: str, img: str, img_bytes: bytes):
    songs = stage / "songs"
    song_dir = songs / song_id
    pack_dir = songs / "pack"
    song_dir.mkdir(parents=True)
    pack_dir.mkdir(parents=True)
    (song_dir / "2.aff").write_text("-\n", encoding="utf-8")
    (songs / "songlist").write_text(json.dumps({"songs": [{"id": song_id, "set": pack_id}]}), encoding="utf-8")
    (songs / "packlist").write_text(json.dumps({"packs": [app.build_packlist_entry(app.PackTemplate(
        pack_id=pack_id,
        name=pack_id,
        description="desc",
        img=img,
        cover_source="auto",
    ))]}), encoding="utf-8")
    (pack_dir / img).write_bytes(img_bytes)


class V21PackLibraryMergeTests(unittest.TestCase):
    def setUp(self):
        self.td = tempfile.TemporaryDirectory()
        self.root = Path(self.td.name)
        self.out = self.root / "out"

    def tearDown(self):
        self.td.cleanup()

    def test_new_pack_is_appended_and_unrelated_resources_are_preserved(self):
        songs = app.library_export_songs_dir(self.out)
        (songs / "pack").mkdir(parents=True)
        (songs / "unlock").write_text("unlock", encoding="utf-8")
        (songs / "pack" / "old.png").write_bytes(b"old")
        (songs / "packlist").write_text(json.dumps({"packs": [{"id": "old", "img": "old.png"}]}), encoding="utf-8")
        stage = self.root / "stage"
        _write_stage(stage, "song_new", "new", "new.png", b"new")

        app.merge_staging_into_library_export(stage, self.out)

        packs = _read_json(songs / "packlist")["packs"]
        self.assertEqual([p["id"] for p in packs], ["old", "new"])
        self.assertEqual((songs / "pack" / "old.png").read_bytes(), b"old")
        self.assertEqual((songs / "pack" / "new.png").read_bytes(), b"new")
        self.assertEqual((songs / "unlock").read_text(encoding="utf-8"), "unlock")

    def test_same_pack_id_replaces_in_place_and_can_overwrite_cover(self):
        songs = app.library_export_songs_dir(self.out)
        (songs / "pack").mkdir(parents=True)
        (songs / "pack" / "same.png").write_bytes(b"old")
        (songs / "packlist").write_text(json.dumps({"packs": [
            {"id": "a", "img": "a.png"},
            {"id": "same", "img": "same.png", "name_localized": {"en": "old"}},
        ]}), encoding="utf-8")
        stage = self.root / "stage"
        _write_stage(stage, "song_same", "same", "same.png", b"new")

        app.merge_staging_into_library_export(stage, self.out)

        packs = _read_json(songs / "packlist")["packs"]
        self.assertEqual([p["id"] for p in packs], ["a", "same"])
        self.assertEqual((songs / "pack" / "same.png").read_bytes(), b"new")

    def test_same_img_different_pack_identical_content_is_allowed(self):
        songs = app.library_export_songs_dir(self.out)
        (songs / "pack").mkdir(parents=True)
        (songs / "pack" / "shared.png").write_bytes(b"same")
        (songs / "packlist").write_text(json.dumps({"packs": [{"id": "old", "img": "shared.png"}]}), encoding="utf-8")
        stage = self.root / "stage"
        _write_stage(stage, "song_new", "new", "shared.png", b"same")

        app.merge_staging_into_library_export(stage, self.out)

        self.assertEqual([p["id"] for p in _read_json(songs / "packlist")["packs"]], ["old", "new"])

    def test_same_img_different_pack_different_content_is_rejected_and_preserved(self):
        songs = app.library_export_songs_dir(self.out)
        (songs / "pack").mkdir(parents=True)
        (songs / "pack" / "shared.png").write_bytes(b"old")
        (songs / "packlist").write_text(json.dumps({"packs": [{"id": "old", "img": "shared.png"}]}), encoding="utf-8")
        stage = self.root / "stage"
        _write_stage(stage, "song_new", "new", "shared.png", b"new")

        with self.assertRaises(RuntimeError):
            app.merge_staging_into_library_export(stage, self.out)

        self.assertEqual((songs / "pack" / "shared.png").read_bytes(), b"old")
        self.assertEqual([p["id"] for p in _read_json(songs / "packlist")["packs"]], ["old"])

    def test_damaged_library_packlist_fails_without_changes(self):
        songs = app.library_export_songs_dir(self.out)
        songs.mkdir(parents=True)
        (songs / "packlist").write_text("{bad json", encoding="utf-8")
        (songs / "songlist").write_text(json.dumps({"songs": []}), encoding="utf-8")
        stage = self.root / "stage"
        _write_stage(stage, "song_new", "new", "new.png", b"new")

        with self.assertRaises(ValueError):
            app.merge_staging_into_library_export(stage, self.out)

        self.assertEqual((songs / "packlist").read_text(encoding="utf-8"), "{bad json")
